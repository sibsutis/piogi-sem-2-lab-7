        public async Task<bool> ToggleRoomLightAsync(int roomId)
        {
            try
            {
                // Самый ваш любимый метод, который переключает состояние света в комнате.
                // Че отправляем? А ничего, просто отправляем запрос на эндпоинт /api/rooms/{roomId}/light, и сервер сам переключает состояние света на противоположное 
                // (если было включено, выключает, если было выключено, включает), и возвращает новое состояние света после переключения.
                // А зачем нам делать отдельный эндпоинт для переключения света? Почему нельзя было просто обновлять состояние света через тот же эндпоинт для обновления сенсоров?
                // Ну, во-первых, это может быть удобнее для пользователя, который просто хочет переключить свет, не заморачиваясь с остальными данными сенсоров.
                // Во-вторых, это может быть полезно для оптимизации, так как переключение света может быть более частой операцией, и отдельный эндпоинт позволяет нам обрабатывать его более эффективно, не затрагивая остальные данные комнаты.
                // (Опять же, как там этот гений на сервере реализовал этот эндпоинт, мы не знаем, но предположим, что он там оптимизировал его для быстрого переключения света, а не для обработки полного обновления комнаты)
                // (Ладно знаем, там так и есть)
                var emptyContent = new StringContent(string.Empty);
                var response = await _httpClient.PatchAsync($"/api/rooms/{roomId}/light", emptyContent);
                response.EnsureSuccessStatusCode();

                return await response.Content.ReadFromJsonAsync<bool>();
            }
            catch (Exception ex)
            {
                throw new Exception($"Ошибка при переключении света: {ex.Message}", ex);
            }
        }

        public async Task DeleteRoomAsync(int roomId)
        {
            try
            {
                // Удаляем комнату по ее ID, отправляя DELETE запрос на эндпоинт /api/rooms/{roomId}. Если сервер успешно удалит комнату, он вернет статус код 200-299, и мы считаем, что удаление прошло успешно.
                // Статус код 204 No Content, который часто используется для успешного удаления, тоже входит в этот диапазон, так что все будет работать.
                var response = await _httpClient.DeleteAsync($"/api/rooms/{roomId}");
                response.EnsureSuccessStatusCode();
            }
            catch (Exception ex)
            {
                throw new Exception($"Ошибка при удалении комнаты: {ex.Message}", ex);
            }
        }
