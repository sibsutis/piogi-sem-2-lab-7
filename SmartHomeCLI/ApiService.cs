using System;
using System.Collections.Generic;
using System.Net.Http;
using System.Net.Http.Json;
using System.Threading.Tasks;
using SmartHomeCLI.DTOs;

namespace SmartHomeCLI
{
    public class ApiService
    {
        // Наш ХТТП клиент для общения с API, по сути почти как браузер, который умеет отправлять запросы и получать ответы от нашего сервера только в виде объектов, а не HTML страниц. 
        // Мы будем использовать его для всех запросов к API.
        private readonly HttpClient _httpClient;

        // Базовый адрес API, по умолчанию http://localhost:5000, но можно переопределить через конструктор ниже
        private readonly string _baseAddress;

        // Конструктор, который позволяет указать базовый адрес API. Если не указать, будет использоваться http://localhost:5000
        // Если вы ничего не меняли в сервере, то этот адрес должен работать. 
        // Если же вы изменили порт или запустили сервер на другом компьютере в сети, то нужно указать соответствующий адрес
        public ApiService(string? baseAddress = null)
        {
            _baseAddress = baseAddress ?? "http://localhost:5000";
            _httpClient = new HttpClient
            {
                BaseAddress = new Uri(_baseAddress),
                Timeout = TimeSpan.FromSeconds(10)  // Устанавливаем таймаут в 10 секунд для всех запросов.
                                                    // Если сервер не отвечает за это время, будет выброшено исключение, которое мы сможем обработать и показать пользователю сообщение об ошибке. 
                                                    // Это поможет избежать бесконечных ожиданий при проблемах с сетью или сервером (а они будут вы же знаете).
            };
        }

        /// <summary>
        /// Проверяет соединение с сервером
        /// </summary>
        public async Task<bool> CheckConnectionAsync()
        {
            try
            {
                // Просто отправляем GET запрос на корневой эндпоинт или любой другой, который гарантированно существует, чтобы проверить, отвечает ли сервер.
                // Вообще для этого можно было бы сделать отдельный эндпоинт /api/health или что-то в этом роде, который бы возвращал статус сервера, но для простоты мы просто проверим любой существующий эндпоинт.
                var response = await _httpClient.GetAsync("/api/apartments");

                // Если сервер отвечает, то статус код должен быть 200-299, и мы считаем, что соединение успешно.
                return response.IsSuccessStatusCode;
            }
            catch
            {
                // Если при попытке соединиться произошла ошибка (например, сервер не запущен, неправильный адрес, проблемы с сетью), то мы ловим исключение и возвращаем false, что означает, что соединение не удалось.
                return false;
            }
        }

