        public async Task<OutUpdateRoomMetadataDto> UpdateRoomMetadataAsync(int roomId, string? name, string? description, string? roomType)
        {
            try
            {
                // Метод для обновления метаданных комнаты (название, описание, тип) по ее ID.
                // Мы отправляем PATCH запрос на эндпоинт /api/rooms/{roomId} с данными, которые хотим обновить, в теле запроса в формате JSON.
                // Что такое ПАТЧ? Опять чета придумал там старый и сидит хайпует.
                // НО ЭТОТ ЭНДПОИНТ ВСЕ МЕНЯЕТ.
                // Метод PATCH в HTTP используется для частичного обновления ресурса.
                // В отличие от PUT, который требует полного представления ресурса, PATCH позволяет отправлять только те поля, которые мы хотим изменить.
                // В нашем случае, если мы хотим обновить только название комнаты, мы можем отправить PATCH запрос с JSON, который содержит только поле "name", и сервер обновит только это поле, не трогая остальные.
                // ВАЖНО: если вы указали какое то поле в запросе, оно будет обновлено на новое значение, даже если это значение null. Или вы такие Description="" - очевидно, значение имеется, пустая строка.
                // Поэтому, если вы не хотите изменять какое то поле, просто не указывайте его в JSON, и сервер оставит его как есть.

                // А еще у нас тут три разных ДТО для обновления комнаты. Почему так, вы очень любите ДТО да?
                // Да, я люблю ДТО, потому что они помогают нам четко определить контракт между клиентом и сервером, и позволяют нам контролировать, какие данные мы отправляем и получаем от сервера.
                // Вот у нас есть InUpdateRoomMetadataDto, который мы используем для отправки данных на сервер при обновлении метаданных комнаты. 
                // Все его поля являются nullable, что позволяет нам отправлять только те поля, которые мы хотим изменить, и не указывать те, которые мы не хотим трогать.

                // А еще он не содержит айди комнаты, потому что айди мы указываем в URL, и сервер его там уже видит, так что нам не нужно его дублировать в теле запроса.
                // Типа, ну, нам бы пришлось передавать айди в теле и в URL, и если бы они не совпадали, то сервер бы не понимал, что делать. 
                // А так, мы просто указываем айди в URL, и сервер знает, какую комнату обновлять, а в теле запроса мы указываем только те поля, которые хотим изменить.
                var payload = new InUpdateRoomMetadataDto
                {
                    Name = name,
                    Description = description,
                    RoomType = roomType
                };

                // Вот ниже пример, в котором я удалил поле. И что будет с этим полем на сервере?       
                // да ничего, оно не будет изменено, так как мы его не указали в JSON, и сервер его просто проигнорирует при обработке запроса.
                // Все. Можем указать только имя например. В этом прелесть метода патч.

                // var payloadWithNoDescription = new InUpdateRoomMetadataDto
                // {
                //     Name = name,
                //     RoomType = roomType
                // };

                var response = await _httpClient.PatchAsJsonAsync($"/api/rooms/{roomId}", payload);
                response.EnsureSuccessStatusCode();

                // А тут возвращается обновленная информация о комнате после изменения метаданных.
                // и да, все отличие между InUpdateRoomMetadataDto и OutUpdateRoomMetadataDto в том, что у второй есть свойство айди, все.
                return await response.Content.ReadFromJsonAsync<OutUpdateRoomMetadataDto>() 
                       ?? throw new Exception("API вернул пустой ответ после обновления метаданных");
            }
            catch (Exception ex)
            {
                throw new Exception($"Ошибка при обновлении метаданных комнаты: {ex.Message}", ex);
            }
        }

        public async Task<OutUpdateSensorDto> UpdateRoomSensorsAsync(int roomId, double? area, double? temperature, bool? lightState)
