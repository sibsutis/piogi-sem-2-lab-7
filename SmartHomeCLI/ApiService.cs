        public async Task<List<ApartmentDto>> GetApartmentsAsync()
        {
            try
            {
                // Отправляем GET запрос на эндпоинт /api/apartments, который должен вернуть список всех квартир. 
                // Мы ожидаем, что сервер вернет JSON массив, который мы можем десериализовать в List<ApartmentDto>.
                // Ну как "мы ожидаем", мы в СВАГГЕРЕ прочитали документацию и знаем, что этот эндпоинт должен возвращать именно это, так что мы уверены в этом.
                // А иначе разработчик сервера не соблюдает контракт API, и тогда уже его проблемы, а не наши (опять же, как бы его, но это же у нас программа не будет работать)
                var apartments = await _httpClient.GetFromJsonAsync<List<ApartmentDto>>("/api/apartments");

                // Если сервер вернул null вместо списка, то мы считаем это ошибкой и выбрасываем исключение, чтобы показать пользователю сообщение об ошибке.
                return apartments ?? throw new Exception("API вернул пустой ответ");
            }
            catch (Exception ex)
            {
                throw new Exception($"Ошибка при получении квартир: {ex.Message}", ex);
            }
        }

        public async Task<ApartmentDto> CreateApartmentAsync(string number, string description)
        {
            try
            {
                // Вот тут первый раз, когда мы отправляем данные на сервер. 
                // Для создания новой квартиры нам нужно отправить POST запрос на эндпоинт /api/apartments с данными новой квартиры в теле запроса в формате JSON.
                // СИШарпик сам превратит наш объект CreateApartmentDto в JSON, а сервер его распарсит и создаст новую квартиру в базе данных.
                var payload = new WriteApartmentDto 
                { 
                    Number = number, 
                    Description = description 
                };

                // "Постим" наш объект на сервер, и если все прошло успешно, то сервер вернет нам JSON с данными новой квартиры, 
                //который мы десериализуем обратно в объект ApartmentDto и возвращаем из метода.
                var response = await _httpClient.PostAsJsonAsync("/api/apartments", payload);
                response.EnsureSuccessStatusCode();
                
                // Почему мы отправляли некий WriteApartmentDto, а не ApartmentDto? 
                // Думаем. Подписаться.
                // Потому что при создании новой квартиры мы не знаем ее ID (он генерируется сервером), и нам не нужно его указывать.
                // С количеством комнат так же, мы их не знаем (и их не будет при создании).
                // Вот для этого и нужен отдельный DTO для создания, который содержит только те поля, которые нужны для создания новой квартиры.
                // Сервер отдаст нам полный объект ДТО.
                return await response.Content.ReadFromJsonAsync<ApartmentDto>() 
                       ?? throw new Exception("API вернул пустой ответ после создания");
            }
            catch (Exception ex)
            {
                throw new Exception($"Ошибка при создании квартиры: {ex.Message}", ex);
            }
        }

        public async Task<ApartmentDto> UpdateApartmentAsync(int id, string number, string description)
        {
            try
            {
                // Также как и выше, контракт API говорит нам, что для обновления квартиры нужно отправить PUT запрос на эндпоинт /api/apartments/{id} с данными квартиры в теле запроса.
                // Мы используем тот же WriteApartmentDto, потому что для обновления нам так же не нужно указывать ID (он уже в URL) и количество комнат (мы его не меняем).
                // А что такое ПУТ?
                var payload = new WriteApartmentDto 
                { 
                    Number = number, 
                    Description = description 
                };

                // Метод PUT в HTTP используется для полного обновления ресурса. 
                // То есть, если мы отправляем PUT запрос, мы должны предоставить полное представление ресурса, который мы хотим обновить.
                // В нашем случае, когда мы обновляем квартиру, мы должны отправить все поля квартиры (кроме ID, который указывается в URL), даже если некоторые из них не изменились.
                // А если не укажем какое то поле, непонятно как сервер обработает это.
                // Он может просто упасть, или занулить значения которые не были указаны, или проигнорировать их и оставить как есть (НО МЫ ЭТОГО НЕ ЗНАЕМ)
                // (НО ВЫ ТО ЗНАЕТЕ У ВАС ЕСТЬ ИСХОДНИКИ СЕРВЕРА, ВЫ МОЖЕТЕ ПОСМОТРЕТЬ КАК ОН ОБРАБАТЫВАЕТ PUT ЗАПРОСЫ И ПОНЯТЬ ЭТО ЕСЛИ ОЧЕНЬ ЗАХОЧЕТЕ)
                var response = await _httpClient.PutAsJsonAsync($"/api/apartments/{id}", payload);
                response.EnsureSuccessStatusCode();

                return await response.Content.ReadFromJsonAsync<ApartmentDto>()
                       ?? throw new Exception("API вернул пустой ответ после обновления");
            }
            catch (Exception ex)
            {
                throw new Exception($"Ошибка при обновлении квартиры: {ex.Message}", ex);
            }
        }

        public async Task DeleteApartmentAsync(int id)
        {
            try
            {
                // Ничего сложного, метод DELETE в HTTP используется для удаления ресурса.
                // Мы отправляем DELETE запрос на эндпоинт /api/apartments/{id}, и если сервер успешно удалил квартиру, 
                // он вернет статус код 200-299, и мы считаем, что удаление прошло успешно.
                // Статус код 204 No Content, который часто используется для успешного удаления, тоже входит в этот диапазон, так что все будет работать.
                // Спойлер: сервер возвращает 204 No Content при успешном удалении, так что мы не получаем никакого тела ответа, и нам не нужно его обрабатывать.
                var response = await _httpClient.DeleteAsync($"/api/apartments/{id}");
                response.EnsureSuccessStatusCode();
            }
            catch (Exception ex)
            {
                throw new Exception($"Ошибка при удалении квартиры: {ex.Message}", ex);
            }
        }

