            try
            {
                // Метод для обновления данных сенсоров комнаты (площадь, температура, состояние света) по ее ID.
                // Аналогично метаданным, мы отправляем PATCH запрос на эндпоинт /api/rooms/{roomId}/sensors с данными, которые хотим обновить, в теле запроса в формате JSON.
                // И так же, как и с метаданными, мы можем отправлять только те поля, которые хотим изменить, и сервер будет обновлять только их, не трогая остальные.
                // А че не пут? Очень удобно обновлять температуру на НОВОЕ значение, но нужно будет указать старый значения полей. 
